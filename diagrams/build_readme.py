"""Generates `diagrams/README.md` from the `.mmd` sources, so the diagrams render on GitHub.

    python diagrams/build_readme.py           # write the file
    python diagrams/build_readme.py --check   # fail if it is out of date (used by CI)

GitHub renders ```mermaid fenced blocks natively, so wrapping each `.mmd` source in one makes
the diagrams viewable in the browser with no image export and no extra dependency. The brief
accepts "a .mmd file or a .md file containing a Mermaid code block", so this is a second
compliant form of the same required deliverable rather than a replacement for it.

The page is generated rather than hand-written for the usual reason: a hand-copied diagram
drifts from its source silently. `--check` in CI makes that impossible.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

DIAGRAMS_DIR = Path(__file__).resolve().parent
OUTPUT = DIAGRAMS_DIR / "README.md"

# Order matters: the system overview reads first, the run trace second.
DIAGRAMS = [
    (
        "architecture.mmd",
        "System architecture",
        "The whole system. The request flows top to bottom through the guardrails, the\n"
        "plan/act/check/repair loop and out to the listener; the two knowledge sources (the\n"
        "notes corpus and the song catalog) feed in from the top; dotted lines are writes to\n"
        "the run log. The `Verification` subgraph at the bottom is where results get checked --\n"
        "by the test suite, the evaluation harness, human review, and CI.",
    ),
    (
        "agent_loop.mmd",
        "The check-and-repair loop",
        "One real run of `python -m src.app \"half an hour of lo-fi to wind down\"`, as a\n"
        "sequence. The first attempt produces a musically sensible list in the wrong order, the\n"
        "critic catches the arc violation that no per-song score could express, and the repair\n"
        "fixes it. Every figure in this diagram comes from the committed log for that run,\n"
        "[`../assets/sample-run-winddown.jsonl`](../assets/sample-run-winddown.jsonl).",
    ),
]

HEADER = """# Architecture diagrams

<!-- Generated by `python diagrams/build_readme.py` from the .mmd sources in this folder.
     Do not edit this file by hand: CI regenerates it and fails if it has drifted. -->

GitHub renders these inline, so they are viewable here without exporting an image. The
authoritative sources are the `.mmd` files alongside this page, which is what the project brief
asks for; this page just wraps each one in a fenced `mermaid` block so it draws in the browser.

To render elsewhere: paste a `.mmd` file into [mermaid.live](https://mermaid.live), or export
an image with
[mermaid-cli](https://github.com/mermaid-js/mermaid-cli) --
`mmdc -i diagrams/architecture.mmd -o assets/architecture.png -b transparent -s 2`.
"""


def strip_leading_comments(source: str) -> str:
    """Drops the `%%` header comments, which are notes to a reader of the source file.

    They explain how to render the file and how to read it, and that context is already in the
    prose on this page, so repeating it inside the rendered block is noise.
    """
    lines = source.splitlines()
    index = 0
    while index < len(lines) and (lines[index].strip().startswith("%%") or not lines[index].strip()):
        index += 1
    return "\n".join(lines[index:]).strip()


def build() -> str:
    parts = [HEADER]
    for filename, title, description in DIAGRAMS:
        path = DIAGRAMS_DIR / filename
        if not path.is_file():
            raise FileNotFoundError(f"missing diagram source: {path}")
        parts.append(f"\n---\n\n## {title}\n")
        parts.append(f"{description}\n")
        parts.append(f"Source: [`{filename}`]({filename})\n")
        parts.append("```mermaid\n" + strip_leading_comments(path.read_text(encoding="utf-8")) + "\n```\n")
    return "\n".join(parts)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="python diagrams/build_readme.py")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if README.md does not match the sources, without writing it",
    )
    args = parser.parse_args(argv)

    rendered = build()

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != rendered:
            print(
                "diagrams/README.md is out of date with the .mmd sources.\n"
                "Run: python diagrams/build_readme.py",
                file=sys.stderr,
            )
            return 1
        print("diagrams/README.md matches the .mmd sources.")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(DIAGRAMS_DIR.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
